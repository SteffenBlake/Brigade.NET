using Dapper;

namespace Brigade.Net.Benchmarks.Api.Fixture;

public static class ApiData
{
    public static readonly string[] Databases = ["sqlserver", "postgresql", "mysql", "mariadb", "sqlite"];

    public static async Task ResetAsync(
        string database,
        string connectionString,
        CancellationToken cancellationToken = default
    )
    {
        await using var connection = ApiDatabasePlatform.CreateConnection(database, connectionString);
        await connection.OpenAsync(cancellationToken);
        var command = new CommandDefinition(
            "DROP TABLE IF EXISTS benchmark_items; DROP TABLE IF EXISTS benchmark_categories;",
            cancellationToken: cancellationToken
        );
        await connection.ExecuteAsync(command);

        var identity = database switch
        {
            "sqlserver" => "bigint IDENTITY(1,1)",
            "postgresql" => "bigint GENERATED BY DEFAULT AS IDENTITY",
            "mysql" or "mariadb" => "bigint AUTO_INCREMENT",
            "sqlite" => "integer",
            _ => throw new ArgumentOutOfRangeException(nameof(database))
        };
        var schema = $"""
            CREATE TABLE benchmark_categories (
                id int NOT NULL PRIMARY KEY,
                name varchar(80) NOT NULL,
                active int NOT NULL,
                min_score int NOT NULL
            );
            CREATE TABLE benchmark_items (
                id {identity} PRIMARY KEY,
                title varchar(80) NOT NULL,
                category_id int NOT NULL,
                score int NOT NULL,
                CONSTRAINT fk_benchmark_category FOREIGN KEY (category_id) REFERENCES benchmark_categories(id)
            );
            CREATE INDEX ix_benchmark_items_category_score ON benchmark_items(category_id, score, id);
            """;
        await connection.ExecuteAsync(new CommandDefinition(schema, cancellationToken: cancellationToken));

        var categories = Enumerable.Range(1, 10).Select(id => new
        {
            id,
            name = $"Category {id}",
            active = id == 10 ? 0 : 1,
            min_score = id % 3 * 10
        });
        await connection.ExecuteAsync(
            new CommandDefinition(
                "INSERT INTO benchmark_categories(id, name, active, min_score) VALUES (@id, @name, @active, @min_score)",
                categories,
                cancellationToken: cancellationToken
            )
        );

        var items = Enumerable.Range(1, 1000).Select(id => new
        {
            title = $"Seed item {id:D5}",
            category_id = id % 9 + 1,
            score = id % 101
        });
        await connection.ExecuteAsync(
            new CommandDefinition(
                "INSERT INTO benchmark_items(title, category_id, score) VALUES (@title, @category_id, @score)",
                items,
                cancellationToken: cancellationToken
            )
        );
    }
}
